suppressPackageStartupMessages({ library(grid); library(gridSVG); library(xml2) })
try_case <- function(label, draw, garnish, strict) {
  pdf(NULL); on.exit(dev.off())
  grid.newpage(); draw(); garnish()
  r <- tryCatch({
    s <- withCallingHandlers(grid.export(NULL, strict = strict)$svg, warning = function(w) invokeRestart("muffleWarning"))
    doc <- read_xml(XML::saveXML(s))
    n <- length(xml_find_all(doc, "//*[@data-row or @class='gar']"))
    sprintf("OK, elements carrying garnish attr: %d", n)
  }, error = function(e) paste("ERROR:", substr(conditionMessage(e), 1, 60)))
  cat(sprintf("%-45s strict=%-5s %s\n", label, strict, r))
}
pts <- function() grid.points(c(.2,.5,.8), c(.2,.5,.8), name = "p", pch = 19)
txt <- function() grid.text(c("a","b","c"), c(.2,.5,.8), .5, name = "t")
pl  <- function() grid.polyline(c(.1,.2,.3,.4), c(.1,.2,.3,.4), id = c(1,1,2,2), name = "pl")
for (st in c(TRUE, FALSE)) {
  try_case("points, per-element data-row", pts, function() grid.garnish("p", `data-row` = c("1","2","3"), group = FALSE), st)
  try_case("points, per-element class", pts, function() grid.garnish("p", class = c("gar","gar","gar"), group = FALSE), st)
  try_case("points, group data-row", pts, function() grid.garnish("p", `data-row` = "all"), st)
  try_case("text, per-element data-row", txt, function() grid.garnish("t", `data-row` = c("1","2","3"), group = FALSE), st)
  try_case("polyline, per-element data-row", pl, function() grid.garnish("pl", `data-row` = c("1","2"), group = FALSE), st)
}
